// C1 : import d'un tableur CSV (colonnes, rapprochement, à vérifier, ajout, annuler, pas de PK) ; export → réimport.
import { withFonts, launch, BASE as E2E, shot, ROOT } from './helpers.mjs';
const browser = await launch();
const res = []; const ok = (l, c) => res.push((c ? '✓ ' : '✗ ') + l); const errors = [];
process.on('uncaughtException', e => { console.log(res.join('\n')); console.log('✗ ERREUR', e.message.split('\n')[0]); process.exit(1); });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 }); await withFonts(ctx);
const page = await ctx.newPage(); page.on('pageerror', e => errors.push(e.message));
const B = E2E + '/?today=2026-10-09&';
const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('pkm-collection-v1') || '{}'));
await page.goto(B + 'start=io', { waitUntil: 'load' }); await page.waitForFunction(() => document.body.innerText.length > 100); await page.waitForTimeout(2500);
const before = await saved();
await page.setInputFiles('#pkm-io-file', new URL('./files/ma-collection.csv', import.meta.url).pathname); await page.waitForTimeout(500);
const sh = page.locator('section[aria-label="Importer un tableur"]');
ok('panneau ouvert : ' + (await sh.locator('h2 + span').innerText()), /ma-collection\.csv · 4 lignes/.test(await sh.innerText()));
const sel = k => sh.locator('select[aria-label="' + k + '"]');
const picked = async k => sel(k).evaluate(s => s.options[s.selectedIndex].text);
ok('colonnes devinées (Nom, Extension, Numéro, Prix payé, État)', (await picked('Nom')) === 'Nom' && (await picked('Extension')) === 'Extension' && (await picked('Numéro')) === 'Numéro' && (await picked('Prix payé')) === 'Prix d\'achat' && (await picked('État')) === 'État');
ok('aperçu normalisé', /Dracaufeu ex · 151 · 199\/165 · ×1 · 120,00.€ · FR · NM · 05\/09/.test((await sh.innerText()).replace(/[  ]/g, ' ')));
await page.screenshot({ path: shot('import-map.png') });
await sh.locator('button:has-text("Rapprocher avec le catalogue")').click(); await page.waitForTimeout(800);
const txt = await sh.innerText();
ok('bilan : ' + txt.split('\n').find(l => /reconnue/.test(l)), /2 reconnues · 1 à vérifier · 1 non reconnue/.test(txt));
ok('non reconnue listée', /Ligne 5 : Zzzqqx inconnu/.test(txt));
const ask = sh.locator('[role="group"][aria-label^="Ligne 4"] button');
ok('à vérifier : propositions + Ignorer (' + await ask.count() + ')', (await ask.count()) >= 2 && /Ignorer/.test(await ask.last().innerText()));
ok('bouton : 3 articles (Pikachu pas encore choisi)', /Ajouter 3 articles/.test(txt));
await ask.first().click(); await page.waitForTimeout(200);
ok('après choix : 4 articles', /Ajouter 4 articles/.test(await sh.innerText()));
await page.screenshot({ path: shot('import-review.png') });
await sh.locator('button:has-text("Ajouter 4 articles")').click(); await page.waitForTimeout(600);
const st = await saved(), imp = st.purchases.filter(a => a.where === 'Import');
ok('3 ajouts « Import » enregistrés', imp.length === 3);
const ch = imp.find(a => a.lines[0].pid === 'sv03.5-199'), mew = imp.find(a => a.lines[0].pid === 'sv03.5-151');
ok('Dracaufeu : date, prix, FR, NM', ch && ch.date === '2026-09-05' && ch.total === 120 && ch.lines[0].lang === 'FR' && ch.lines[0].cond === 'NM');
ok('Mew : ×2, EN, Excellent', mew && mew.lines[0].qty === 2 && mew.lines[0].lang === 'EN' && mew.lines[0].cond === 'EX');
ok('pas de PK pour un import (' + before.pk + ' → ' + st.pk + ')', st.pk === before.pk);
const toast = page.locator('[role="status"]').last();
ok('message « 4 articles importés » avec Annuler', /4 articles importés · collection à/.test(await toast.innerText()) && (await toast.locator('button:has-text("Annuler")').count()) === 1);
await toast.locator('button:has-text("Annuler")').click(); await page.waitForTimeout(400);
ok('Annuler retire l’import', !(await saved()).purchases.some(a => a.where === 'Import'));
ok('aucune erreur JS', errors.length === 0);
console.log(res.join('\n')); if (errors.length) console.log('Erreurs :', errors);
await browser.close();

// B1 : cote selon l'état et la langue (valeur de la collection, fiche, Réglages) ; B2 : vendre un exemplaire précis.
import { withFonts, launch, BASE as E2E, shot, ROOT } from './helpers.mjs';
const browser = await launch();
const res = []; const ok = (l, c) => res.push((c ? '✓ ' : '✗ ') + l); const errors = [];
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 }); await withFonts(ctx);
const page = await ctx.newPage(); page.on('pageerror', e => errors.push(e.message));
const B = E2E + '/?today=2026-10-09&';
const eur = t => Number(String(t).replace(/[^\d,-]/g, '').replace(',', '.'));
const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('pkm-collection-v1') || '{}'));
const total = async () => eur(await page.locator('section[aria-label="Ma collection"], [aria-label="Valeur de la collection"]').first().locator('text=/€/').first().innerText().catch(() => '0'));
const homeValue = async () => { await page.goto(B, { waitUntil: 'load' }); await page.waitForTimeout(1500); return eur((await page.locator('#app').innerText()).match(/Ma collection\s*\n?\s*([\d\s  ]+,\d\d)\s*€/)[1]); };
const v0 = await homeValue();
ok('valeur de départ : ' + v0, v0 > 0);
// k1 passe en « Joué » par D5.
await page.goto(B + 'start=item&itemId=k1', { waitUntil: 'load' }); await page.waitForTimeout(1200);
const hist = page.locator('section[aria-label="Historique d’achat"]');
const cote = eur((await page.locator('#app').innerText()).match(/Cote Dropicards[^\n]*\n?[^\d]*([\d\s ]+,\d\d)/)?.[1] || '0');
await hist.locator('button[aria-label^="Modifier l’ajout du"]').first().click(); await page.waitForTimeout(250);
const sh = page.locator('section[aria-label="Modifier l’ajout"]');
await sh.locator('[aria-label="État de l’exemplaire"] button:has-text("Joué")').click();
await sh.locator('button:has-text("Enregistrer les modifications")').click(); await page.waitForTimeout(500);
const toastTxt = (await page.locator('[role="status"]').last().innerText()).replace(/[\u202f\u00a0]/g, ' ');
const note = await hist.innerText();
ok('fiche : valeur de tes exemplaires (Joué 55 %)', /Valeur de tes exemplaires : 1 × FR Joué \(55 %\) = .+ au lieu de .+ en Near Mint/.test(note));
await page.screenshot({ path: shot('value-item.png') });
const m = note.match(/= ([\d,]+)\s*€ au lieu de ([\d,]+)\s*€/);
const adj = eur(m[1]), raw = eur(m[2]);
ok('55 % de la cote : ' + adj + ' / ' + raw, Math.abs(adj - raw * 0.55) < 0.011);
const v1 = await homeValue();
ok('message : collection à la nouvelle valeur (' + toastTxt.replace(/\n/g, ' ') + ')', toastTxt.indexOf(v1.toFixed(2).replace('.', ',').replace(/\B(?=(\d{3})+(?!\d))/g, ' ')) >= 0);
ok('valeur de la collection baisse de 45 % de la carte : ' + v0 + ' → ' + v1, Math.abs((v0 - v1) - raw * 0.45) < 0.02);
// Réglages : interrupteur.
await page.goto(B + 'start=settings', { waitUntil: 'load' }); await page.waitForTimeout(1200);
const sw = page.locator('button[role="switch"]:has-text("Selon l’état et la langue")');
ok('Réglages : interrupteur activé et règle', (await sw.getAttribute('aria-checked')) === 'true' && /Joué 55 %/.test(await page.locator('#app').innerText()));
await sw.scrollIntoViewIfNeeded(); await page.screenshot({ path: shot('value-settings.png') });
await sw.click(); await page.waitForTimeout(300);
ok('désactivé', (await sw.getAttribute('aria-checked')) === 'false' && (await saved()).valAdj === false);
const v2 = await homeValue();
ok('cote brute : valeur de départ retrouvée (' + v2 + ')', Math.abs(v2 - v0) < 0.011);
await page.goto(B + 'start=settings', { waitUntil: 'load' }); await page.waitForTimeout(1000);
await page.locator('button[role="switch"]:has-text("Selon l’état et la langue")').click(); await page.waitForTimeout(300);
// B2 : vendre l'exemplaire de l'ajout a6 (175 €).
await page.goto(B + 'start=item&itemId=p1', { waitUntil: 'load' }); await page.waitForTimeout(1200);
await page.click('button:has-text("J’ai vendu")'); await page.waitForTimeout(400);
const grp = page.locator('[aria-label="Exemplaire vendu"] button');
const opts = (await grp.allInnerTexts()).map(o => o.replace(/[\u202f\u00a0\n]+/g, ' '));
ok("choix de l’exemplaire : " + opts.join(" | "), opts.length === 3 && /Peu importe/.test(opts[0]) && opts.some(o => /175,00 € \/ u · reste 1/.test(o)) && opts.some(o => /162,00 € \/ u · reste 1/.test(o)));
await grp.filter({ hasText: '175,00' }).click(); await page.waitForTimeout(200);
await page.fill('input[placeholder="0,00"]', '200'); await page.locator('input[placeholder="0,00"]').dispatchEvent('change'); await page.waitForTimeout(250);
const sheetTxt = await page.locator('#app').innerText();
ok('coût : cet exemplaire (175,00 €)', /Coût d’achat de cet exemplaire \(175,00/.test(sheetTxt));
await page.locator('button[aria-label="Augmenter la quantité"]').last().click(); await page.waitForTimeout(250);
ok('quantité 2 : refus « Il ne reste que 1 exemplaire de cet ajout »', /Il ne reste que 1 exemplaire de cet ajout/.test(await page.locator('#app').innerText()));
await page.locator('button[aria-label="Diminuer la quantité"]').last().click(); await page.waitForTimeout(250);
await page.locator('[aria-label="Exemplaire vendu"]').scrollIntoViewIfNeeded(); await page.screenshot({ path: shot('value-sell.png') });
await page.click('button:has-text("Enregistrer la vente")'); await page.waitForTimeout(500);
const st = await saved(), sale = st.sales[st.sales.length - 1];
ok('vente enregistrée avec l’ajout a6, datée du jour', sale.from === 'a6' && sale.date === '2026-10-09');
ok('marge sur son prix d’achat : ' + (await page.locator('[role="status"]').last().innerText()), /marge nette \+23,50/.test(await page.locator('[role="status"]').last().innerText()));
// D5 : l'ajout a6 est désigné par la vente, sa suppression est refusée.
await page.goto(B + 'start=item&itemId=p1', { waitUntil: 'load' }); await page.waitForTimeout(1200);
const rows = page.locator('section[aria-label="Historique d’achat"] button[aria-label="Modifier l’ajout du 20/09"]');
await rows.first().click(); await page.waitForTimeout(250);
await sh.locator('button:has-text("Supprimer cet ajout")').click(); await sh.locator('button:has-text("Oui, supprimer")').click(); await page.waitForTimeout(300);
ok('suppression refusée : vente qui désigne l’ajout', /désigne un exemplaire de cet ajout/.test(await sh.innerText()));
ok('aucune erreur JS', errors.length === 0);
console.log(res.join('\n')); if (errors.length) console.log('Erreurs :', errors);
await browser.close();

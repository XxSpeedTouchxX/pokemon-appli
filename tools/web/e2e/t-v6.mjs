import { launch, BASE as E2E, shot as OUTF, ROOT } from './helpers.mjs';
const browser = await launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3 });
const requested = [];
// Images TCGdex inaccessibles ici : on renvoie une carte factice de la bonne taille, et on note les adresses demandées.
await ctx.route('https://assets.tcgdex.net/**', route => {
  const u = route.request().url(); requested.push(u);
  const logo = /\/logo\.(webp|png)$/.test(u), w = logo ? 300 : /low\./.test(u) ? 245 : 600, h = logo ? 120 : /low\./.test(u) ? 337 : 825;
  const tag = /high\.png$/.test(u) ? 'PNG HQ' : /high\.webp$/.test(u) ? 'WEBP HQ' : logo ? 'LOGO' : 'low';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#F6D365"/><stop offset="1" stop-color="#FDA085"/></linearGradient></defs><rect width="${w}" height="${h}" rx="${w * 0.045}" fill="url(#g)"/><rect x="${w * 0.07}" y="${h * 0.1}" width="${w * 0.86}" height="${h * 0.42}" fill="#ffffff" opacity="0.55"/><text x="${w / 2}" y="${h * 0.7}" font-size="${w * 0.1}" text-anchor="middle" font-family="sans-serif" fill="#3a2a00">${tag}</text></svg>`;
  route.fulfill({ status: 200, contentType: 'image/svg+xml', body: svg });
});
const page = await ctx.newPage();
const errors = [], steps = [];
page.on('pageerror', e => errors.push('pageerror: ' + e.message));
page.on('console', m => { if (m.type() === 'error' && !/Failed to load resource|fonts\.g/.test(m.text())) errors.push('console: ' + m.text()); });
page.on('dialog', d => d.accept());
const ok = (k, v) => steps.push((v ? '✓ ' : '✗ ') + k);
const has = async t => (await page.locator('text=' + t).count()) > 0;
const shot = async n => page.screenshot({ path: OUTF(n + '.png') });
const step = async (name, fn) => { try { await fn(); } catch (e) { ok(name + ' — ÉCHEC : ' + e.message.split('\n')[0], false); } };

await step('marché', async () => {
  await page.goto(E2E + '/?start=search', { waitUntil: 'load' });
  await page.waitForSelector('button:has-text("Toutes les cartes")', { timeout: 10000 });
  ok('bandeau : ' + (await page.locator('button:has-text("Toutes les cartes")').innerText()).replace(/\n/g, ' | '), true);
  await page.waitForTimeout(300); await shot('v6-marche');
});
await step('extensions', async () => {
  await page.click('button:has-text("Toutes les cartes")');
  await page.waitForSelector('nav[aria-label="Aller à une série"]', { timeout: 20000 });
  const groups = await page.locator('main section[id^="pkm-ser-"]').evaluateAll(g => g.map(x => x.getAttribute('aria-label')));
  ok('« Toutes les cartes » mène à « Toutes les séries » (' + groups.length + ') : ' + groups.slice(0, 4).join(', ') + ' … ' + groups.slice(-2).join(', '), groups.length > 5 && groups[groups.length - 1] === 'Sans version française');
  await page.waitForTimeout(300); await shot('v6-extensions');
  await page.fill('input[aria-label="Rechercher une série ou une extension"]', 'etincelles'); await page.waitForTimeout(300);
  ok('recherche extension : ' + (await page.locator('main section[id^="pkm-ser-"] div.pkm-rise > button').count()) + ' extension(s)', (await page.locator('main section[id^="pkm-ser-"] div.pkm-rise > button').count()) >= 1);
});
await step('grille', async () => {
  await page.locator('button[aria-label^="Étincelles Déferlantes,"]').click();
  await page.waitForSelector('text=Série complète');
  ok('extension : ' + (await page.locator('section[aria-label="Extension"]').innerText()).replace(/\n/g, ' | '), true);
  const tiles = await page.locator('main button[aria-label*=", n° "]').count();
  ok('grille : ' + tiles + ' cartes', tiles > 200);
  await page.waitForTimeout(600); await shot('v6-grille');
  const srcs = await page.evaluate(() => [...document.querySelectorAll('main img[srcset]')].slice(0, 3).map(i => i.currentSrc));
  ok('grille en écran 3x → ' + srcs.map(u => u.split('/').slice(-2).join('/')).join(', '), srcs.length && srcs.every(u => /high\.webp$/.test(u)));
  // Tri par cote (2026-10-17 : bouton « Tri », qui passe de numéro à cote, puis nom).
  await page.click('button:has-text("Tri : numéro")');
  const first = await page.locator('main button[aria-label*=", n° "]').first().getAttribute('aria-label');
  ok('tri par cote : ' + first, /cote/.test(first));
  await page.click('button:has-text("Tri : cote")'); await page.click('button:has-text("Tri : nom")');
});
await step('fiche et zoom', async () => {
  await page.evaluate(() => { document.querySelector('#app main').scrollTop = 1500; });
  await page.waitForTimeout(150);
  await page.locator('main button[aria-label*="n° 238/191"]').first().click();
  await page.waitForSelector('button[aria-label^="Agrandir la carte"]');
  const big = await page.locator('button[aria-label^="Agrandir la carte"] img').getAttribute('src');
  ok('fiche en PNG haute qualité : ' + big.split('/').slice(-3).join('/'), /high\.png$/.test(big));
  const box = await page.locator('button[aria-label^="Agrandir la carte"]').boundingBox();
  ok('carte entière ' + Math.round(box.width) + '×' + Math.round(box.height), Math.abs(box.width / box.height - 600 / 825) < 0.01);
  ok('en haut de la fiche', (await page.evaluate(() => document.querySelector('#app main').scrollTop)) === 0);
  await page.waitForTimeout(400); await shot('v6-fiche');
  await page.click('button[aria-label^="Agrandir la carte"]');
  await page.waitForSelector('[role="dialog"]');
  await page.waitForTimeout(300);
  const zb = await page.locator('[role="dialog"] img').boundingBox();
  ok('zoom ' + Math.round(zb.width) + '×' + Math.round(zb.height) + ' : ' + (await page.locator('[role="dialog"]').innerText()).replace(/\n/g, ' | '), zb.width > 300);
  await shot('v6-zoom');
  ok('focus sur « Fermer »', (await page.evaluate(() => document.activeElement && document.activeElement.getAttribute('aria-label'))) === 'Fermer');
  await page.keyboard.press('Escape');
  await page.waitForTimeout(100);
  ok('Échap ferme le zoom', (await page.locator('[role="dialog"]').count()) === 0);
  ok('focus revenu sur la carte', /^Agrandir la carte/.test(await page.evaluate(() => document.activeElement && document.activeElement.getAttribute('aria-label'))));
});
await step('ajout', async () => {
  await page.click('button:has-text("+ Ajouter un exemplaire")'); await page.waitForTimeout(150);
  await page.locator('button:has-text("Ajouter à ma collection")').last().click(); await page.waitForTimeout(200);
  ok('ajout : ' + (await page.locator('[role="status"]').allInnerTexts()).join(' '), await has('ajouté'));
  await page.click('button[aria-label="Retour"]');
  await page.waitForSelector('text=Série complète');
  await page.waitForTimeout(250);
  const st = await page.evaluate(() => document.querySelector('#app main').scrollTop);
  ok('retour : l’extension reprend sa position (2026-10-11, avant : en haut) : ' + st, st > 0);
  ok('badge ×1 dans la grille', (await page.locator('main button[aria-label*="n° 238/191"]').first().innerText()).includes('×1'));
});
await step('rechargement', async () => {
  await page.waitForTimeout(500);
  await page.goto(E2E + '/?start=home', { waitUntil: 'load' });
  await page.waitForTimeout(800);
  ok('après rechargement, la carte est toujours là (classeur)', (await page.locator('section[aria-label="Mon classeur"] button[aria-label^="Pikachu-ex"]').count()) > 0);
  await page.waitForTimeout(400); await shot('v6-collection');
});
await step('vider / démo', async () => {
  await page.goto(E2E + '/?start=settings', { waitUntil: 'load' });
  ok('réglages : ' + await page.locator('section[aria-label="Ma collection sur cet appareil"] p').innerText(), await has('Enregistrée automatiquement'));
  await page.click('button:has-text("Vider ma collection")'); await page.waitForTimeout(500);
  await page.goto(E2E + '/?start=home', { waitUntil: 'load' });
  ok('collection vide après rechargement', await has('Aucune carte dans ton classeur'));
  ok('pas de blocs vides', !(await has('Mes plus belles pièces')) && !(await has('Derniers ajouts')) && !(await has('Plus forte hausse')));
  await page.waitForTimeout(300); await shot('v6-accueil-vide');
  await page.goto(E2E + '/?start=collection&r=1', { waitUntil: 'load' }); await page.waitForTimeout(1500);
  ok('collection vide : « Toutes les séries » à 0 %', await has('Toutes les séries') && /0\/[\d\s\u202f]+ · 0 %/.test(await page.locator('main').innerText()));
  await page.goto(E2E + '/?start=settings', { waitUntil: 'load' });
  await page.click('button:has-text("Remettre la démo")'); await page.waitForTimeout(500);
  await page.goto(E2E + '/?start=home', { waitUntil: 'load' });
  ok('démo remise', (await page.locator('section[aria-label="Mon classeur"] [role="tabpanel"] button[aria-label$="Ouvrir la fiche"]').count()) >= 6);
  await page.goto(E2E + '/?demo=novice', { waitUntil: 'load' }); ok('démo novice affichée : ' + await page.locator('main section').first().innerText().then(t => t.split('\n').slice(0, 3).join(' | ')), true); await page.click('button:has-text("Ajouter")').catch(() => {});
  await page.goto(E2E + '/?start=settings', { waitUntil: 'load' });
  ok('lien #novice sans effet : ' + await page.locator('section[aria-label="Ma collection sur cet appareil"] p').innerText(), !(await has('· 3 articles')));
});
await step('anglais et sous-extensions', async () => {
  await page.goto(E2E + '/?start=set&setId=gym1', { waitUntil: 'load' });
  await page.waitForSelector('main .pkm-sv-card');
  ok('Gym Heroes : ' + await page.locator('main p').first().innerText(), await has('version française'));
  await page.locator('main button[aria-label*=", n° "]').first().click();
  await page.waitForSelector('button[aria-label^="Agrandir la carte"]');
  ok('carte EN : ' + (await page.locator('main p').first().innerText()).slice(0, 100), await has('Carte en anglais'));
  await page.goto(E2E + '/?start=set&setId=swsh9tg', { waitUntil: 'load' });
  await page.waitForSelector('main .pkm-sv-card');
  ok('Galerie de dresseurs : ' + (await page.locator('main').innerText()).split('\n').slice(0, 4).join(' | '), true);
  const hscroll = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  ok('pas de défilement horizontal', !hscroll);
});
const kinds = { 'low.webp': 0, 'high.webp': 0, 'high.png': 0, logo: 0 };
requested.forEach(u => { if (/\/logo\./.test(u)) kinds.logo++; else for (const k of ['low.webp', 'high.webp', 'high.png']) if (u.endsWith(k)) kinds[k]++; });
ok('images demandées : ' + JSON.stringify(kinds), true);
console.log(steps.join('\n'));
console.log(errors.length ? 'ERREURS\n' + errors.join('\n') : 'aucune erreur');
await browser.close();
